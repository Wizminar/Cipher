// Turns the raw word lists in scripts/raw/ into ES modules under js/data/.
// Run with: node scripts/build-data.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = (f) => readFileSync(join(root, "scripts/raw", f), "utf8");
const out = join(root, "js/data");
mkdirSync(out, { recursive: true });

const clean = (list, { min = 1, max = 32, re = /^[a-z0-9]+$/ } = {}) => {
  const seen = new Set();
  const res = [];
  for (let w of list) {
    w = w.trim().toLowerCase();
    if (w.length < min || w.length > max || !re.test(w) || seen.has(w)) continue;
    seen.add(w);
    res.push(w);
  }
  return res;
};

const lists = {
  passwords: clean(raw("passwords.txt").split("\n"), { min: 3 }),
  english: clean(raw("english.txt").split("\n"), { min: 3, re: /^[a-z]+$/ }),
  names: clean(raw("names.txt").split("\n"), { min: 3, re: /^[a-z]+$/ }),
};

const header = "// Generated by scripts/build-data.mjs. Do not edit by hand.\n";
for (const [name, words] of Object.entries(lists)) {
  writeFileSync(join(out, `${name}.js`), `${header}export default ${JSON.stringify(words.join(" "))};\n`);
  console.log(`${name}: ${words.length} words`);
}

const eff = raw("eff.txt").split("\n").map((l) => l.split("\t")[1]?.trim()).filter(Boolean);
if (eff.length !== 7776) throw new Error(`EFF list should have 7776 words, got ${eff.length}`);
writeFileSync(join(out, "eff.js"), `${header}export default ${JSON.stringify(eff.join(" "))};\n`);
console.log(`eff: ${eff.length} words`);
