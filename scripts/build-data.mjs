// Turns the raw word lists in scripts/raw/ into the WORDLISTS block at the end
// of script.js. Run with: npm run build:data
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = (f) => readFileSync(join(root, "scripts/raw", f), "utf8");

const clean = (list, { min = 1, max = 32, re = /^[a-z0-9]+$/ } = {}) => {
  const seen = new Set();
  const res = [];
  for (let w of list) {
    w = w.trim().toLowerCase();
    if (w.length < min || w.length > max || !re.test(w) || seen.has(w)) continue;
    seen.add(w);
    res.push(w);
  }
  return res;
};

const lists = {
  passwords: clean(raw("passwords.txt").split("\n"), { min: 3 }),
  english: clean(raw("english.txt").split("\n"), { min: 3, re: /^[a-z]+$/ }),
  names: clean(raw("names.txt").split("\n"), { min: 3, re: /^[a-z]+$/ }),
  eff: raw("eff.txt").split("\n").map((l) => l.split("\t")[1]?.trim()).filter(Boolean),
};
if (lists.eff.length !== 7776) throw new Error(`EFF list should have 7776 words, got ${lists.eff.length}`);

const scriptPath = join(root, "script.js");
const script = readFileSync(scriptPath, "utf8");
const begin = script.indexOf("// <word-lists>");
const end = script.indexOf("// </word-lists>");
if (begin < 0 || end < 0) throw new Error("Word-list markers not found in script.js");

const block =
  "// <word-lists> generated by scripts/build-data.mjs, do not edit by hand\nconst WORDLISTS = {\n" +
  Object.entries(lists).map(([k, words]) => `  ${k}: ${JSON.stringify(words.join(" "))},\n`).join("") +
  "};\n";
writeFileSync(scriptPath, script.slice(0, begin) + block + script.slice(end));
for (const [k, words] of Object.entries(lists)) console.log(`${k}: ${words.length} words`);
